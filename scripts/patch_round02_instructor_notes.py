def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    sections = data.get("sections") or data.get("implemented_sections")
    if not isinstance(sections, list):
        raise SystemExit("sections not found")

    for sec in sections:
        sn = sec.get("section_number")
        for q in sec.get("questions", []):
            qid = q.get("question_id")
            key = (sn, qid)
            expl = q.get("explanation")
            if not isinstance(expl, dict):
                continue
            if key in UPDATES:
                expl["instructor_note"] = UPDATES[key]
            if sn == 5 and qid == "問4":
                q["answer"] = "②"
            if sn == 7 and qid == "問3":
                q["answer"] = "②"

    DATA.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print("patched:", DATA)


if __name__ == "__main__":
    main()
